import { chromium } from 'playwright';
import { pathToFileURL } from 'node:url';
const input = process.argv[2];
const url = pathToFileURL(input).href;
const browser = await chromium.launch({ headless: true });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, javaScriptEnabled: false });
const page = await ctx.newPage();
const requests = [];
page.on('request', r => requests.push(r.url()));
page.on('requestfailed', r => console.log('FAILED:', r.url(), r.failure()?.errorText));
await page.goto(url, { waitUntil: 'load' });
await page.locator('.me').scrollIntoViewIfNeeded();
await page.waitForFunction(() => document.querySelector('.me-photo img')?.naturalWidth > 0);
const r = await page.evaluate(() => {
  const out = {};
  out.title = document.title;
  out.heroImg = document.querySelector('.hero-portrait img') ? getComputedStyle(document.querySelector('.hero-portrait img')).backgroundImage : 'NO IMG';
  out.heroImgNat = document.querySelector('.hero-portrait img')?.naturalWidth || 0;
  out.meImgNat = document.querySelector('.me-photo img')?.naturalWidth || 0;
  out.h1 = document.querySelector('h1')?.innerText;
  out.fontFamily = getComputedStyle(document.body).fontFamily;
  out.faq = document.querySelectorAll('#faq details').length;
  out.revealOpacities = [...document.querySelectorAll('.reveal')].map(e => getComputedStyle(e).opacity);
  out.imgCount = document.querySelectorAll('img').length;
  out.imgVisible = [...document.querySelectorAll('img')].map(i => ({ srcStart: i.src.slice(0, 40), width: i.naturalWidth, complete: i.complete }));
  out.meText = document.querySelector('.me-copy p')?.textContent.trim();
  out.meLink = document.querySelector('.me-link')?.getAttribute('href');
  out.fontsCss = [...document.querySelectorAll('style')].map(s => s.textContent.slice(0, 80));
  out.outsideReqs = [];  // filled from outside
  return out;
});
console.log('---');
console.log('TITLE:', r.title);
console.log('H1:', r.h1);
console.log('FONT:', r.fontFamily);
console.log('FAQ details:', r.faq);
console.log('Reveal opacities (без JS):', r.revealOpacities.length, 'элементов, мин =', Math.min(...r.revealOpacities.map(Number)));
console.log('IMG count:', r.imgCount, 'visible:', r.imgVisible);
console.log('Personal portrait natural width:', r.meImgNat);
console.log('Personal block:', r.meText, r.meLink);
console.log('Style block count:', r.fontsCss.length);
console.log('Requests issued:', requests.length);
const externalReqs = requests.filter(u => !u.startsWith('data:') && !u.startsWith('file:'));
console.log('External/local-file requests:', externalReqs);
await browser.close();
